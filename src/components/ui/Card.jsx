import "./Card.css";

/**
 * Базовый модуль-карточка. Все крупные блоки карточки клиента
 * (шапка роли, идентификация, каталог, шапка раздела, контент)
 * — это отдельные <Card>, а не один общий контейнер. Так их
 * проще независимо показывать/скрывать и переиспользовать.
 *
 * tone позволяет подсветить карточку как предупреждение/ошибку
 * (например, статус активной блокировки) без отдельного компонента.
 */
export function Card({ as: Tag = "div", tone = "default", className = "", children, ...rest }) {
  return (
    <Tag className={`card card-${tone} ${className}`} {...rest}>
      {children}
    </Tag>
  );
}
